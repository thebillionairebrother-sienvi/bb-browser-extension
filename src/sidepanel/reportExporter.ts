export interface LegalTechnicalities {
  summary: string;
  dos: string[];
  donts: string[];
  complianceRisk: 'low' | 'medium' | 'high' | string;
}

export interface SeasonalRelevance {
  applicable: boolean;
  currentSeason?: string;
  misalignment?: string[];
  suggestedSeasonalMoves?: string[];
}

export interface AuditResult {
  whatThisPageSells: string;
  whoItIsFor: string;
  whatIsStrong: string[];
  whatIsWeak: string[];
  topConversionLeaks: string[];
  bestNextMove: string;
  legalTechnicalities?: LegalTechnicalities;
  seasonalRelevance?: SeasonalRelevance;
}

export interface PageSnapshot {
  url: string;
  title: string;
  metaDescription?: string;
  subPages?: any[];
}

function cleanText(text: string): string {
  return (text || '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201c\u201d]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/[^\x20-\x7E\n]/g, '')
    .replace(/[ \t]+/g, ' ')
    .trim();
}

function scopeLabel(scope: string): string {
  if (scope === 'domain') return 'Entire Website';
  if (scope === 'subpath') return 'Sub-pages';
  return 'Active Page';
}

export function generateTextReport(
  result: AuditResult,
  snapshot: PageSnapshot | null,
  scope: string
): string {
  const lines: string[] = [
    'BILLIONAIRE BROTHER - STRATEGIC AUDIT REPORT',
    `Target URL: ${snapshot?.url || 'N/A'}`,
    `Audit Scope: ${scopeLabel(scope)}`,
    `Generated: ${new Date().toLocaleString()}`,
  ];

  if (snapshot?.subPages?.length) {
    lines.push(`Sub-pages: Cross-analyzed ${snapshot.subPages.length} additional key site pages`);
  }

  const section = (title: string, value: string) => {
    lines.push('', title.toUpperCase(), cleanText(value || 'N/A'));
  };
  const list = (title: string, items: string[], numbered = false) => {
    lines.push('', title.toUpperCase());
    if (!items?.length) {
      lines.push('None identified.');
      return;
    }
    items.forEach((item, index) => lines.push(`${numbered ? `${index + 1}.` : '-'} ${cleanText(item)}`));
  };

  section(`What This ${scope === 'domain' ? 'Website' : 'Page'} Sells`, result.whatThisPageSells);
  section('Target Audience', result.whoItIsFor);
  list("What's Working Strong", result.whatIsStrong);
  list('Conversion Bottlenecks & Weaknesses', result.whatIsWeak);
  list('Top Revenue Leaks', result.topConversionLeaks, true);

  if (result.legalTechnicalities) {
    const legal = result.legalTechnicalities;
    section("Derek's Legal & Technicalities Audit", legal.summary);
    lines.push(`Compliance Risk Level: ${cleanText(legal.complianceRisk || 'medium').toUpperCase()}`);
    list('Legal DOs & Compliance Strengths', legal.dos);
    list('Legal DONTs & Technical Risks', legal.donts);
  }

  if (result.seasonalRelevance?.applicable) {
    const seasonal = result.seasonalRelevance;
    section('Seasonal Relevance', seasonal.currentSeason ? `Current retail season: ${seasonal.currentSeason}` : 'N/A');
    list('Seasonal Misalignment', seasonal.misalignment || []);
    list('Suggested Seasonal Moves', seasonal.suggestedSeasonalMoves || []);
  }

  section('Best Next Action', result.bestNextMove);
  lines.push('', 'Generated by Billionaire Brother Audit Engine');
  return lines.join('\n');
}

export async function copyTextReport(
  result: AuditResult,
  snapshot: PageSnapshot | null,
  scope: string
): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(generateTextReport(result, snapshot, scope));
    return true;
  } catch (error) {
    console.error('Failed to copy text report to clipboard:', error);
    return false;
  }
}

interface PdfLine {
  text: string;
  bold?: boolean;
  size?: number;
  gapAfter?: number;
}

function wrapText(text: string, maxCharacters: number): string[] {
  const words = cleanText(text).split(/\s+/).filter(Boolean);
  const lines: string[] = [];
  let current = '';
  for (const word of words) {
    if (!current) current = word;
    else if (`${current} ${word}`.length <= maxCharacters) current += ` ${word}`;
    else {
      lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines.length ? lines : ['N/A'];
}

function pdfEscape(text: string): string {
  return cleanText(text).replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function buildPdf(lines: PdfLine[]): Uint8Array {
  const pageWidth = 595;
  const pageHeight = 842;
  const left = 48;
  const top = 58;
  const bottom = 48;
  const pageStreams: string[] = [];
  let commands: string[] = [];
  let y = pageHeight - top;

  const finishPage = () => {
    commands.push('0.78 0.64 0.15 RG', `48 36 m ${pageWidth - 48} 36 l S`);
    pageStreams.push(commands.join('\n'));
    commands = [];
    y = pageHeight - top;
  };

  for (const line of lines) {
    const size = line.size || 10;
    const leading = size + 4;
    if (y - leading < bottom) finishPage();
    const font = line.bold ? 'F2' : 'F1';
    const color = line.bold ? '0.12 0.12 0.14' : '0.22 0.22 0.24';
    commands.push(
      'BT',
      `/${font} ${size} Tf`,
      `${color} rg`,
      `1 0 0 1 ${left} ${y} Tm`,
      `(${pdfEscape(line.text)}) Tj`,
      'ET'
    );
    y -= leading + (line.gapAfter || 0);
  }
  finishPage();

  const pageObjectNumbers = pageStreams.map((_, index) => 5 + index * 2);
  const objects: string[] = [];
  objects[1] = '<< /Type /Catalog /Pages 2 0 R >>';
  objects[2] = `<< /Type /Pages /Count ${pageStreams.length} /Kids [${pageObjectNumbers.map(n => `${n} 0 R`).join(' ')}] >>`;
  objects[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>';
  objects[4] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>';

  pageStreams.forEach((stream, index) => {
    const pageNumber = pageObjectNumbers[index];
    const contentNumber = pageNumber + 1;
    objects[pageNumber] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentNumber} 0 R >>`;
    objects[contentNumber] = `<< /Length ${new TextEncoder().encode(stream).length} >>\nstream\n${stream}\nendstream`;
  });

  const encoder = new TextEncoder();
  let pdf = '%PDF-1.4\n%BB-Audit\n';
  const offsets: number[] = [0];
  for (let number = 1; number < objects.length; number++) {
    offsets[number] = encoder.encode(pdf).length;
    pdf += `${number} 0 obj\n${objects[number]}\nendobj\n`;
  }
  const xrefOffset = encoder.encode(pdf).length;
  pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let number = 1; number < objects.length; number++) {
    pdf += `${offsets[number].toString().padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  return encoder.encode(pdf);
}

function reportLines(result: AuditResult, snapshot: PageSnapshot | null, scope: string): PdfLine[] {
  const lines: PdfLine[] = [
    { text: 'BILLIONAIRE BROTHER', bold: true, size: 18 },
    { text: 'Webpage Strategic Audit Report', size: 11, gapAfter: 8 },
    { text: `Target URL: ${snapshot?.url || 'N/A'}`, size: 8 },
    { text: `Scope: ${scopeLabel(scope)} | Generated: ${new Date().toLocaleDateString()}`, size: 8, gapAfter: 10 },
  ];

  const section = (title: string, text: string) => {
    lines.push({ text: title, bold: true, size: 12, gapAfter: 2 });
    wrapText(text || 'N/A', 92).forEach(value => lines.push({ text: value, size: 9 }));
    lines.push({ text: '', size: 4, gapAfter: 4 });
  };
  const list = (title: string, items: string[], numbered = false) => {
    lines.push({ text: title, bold: true, size: 12, gapAfter: 2 });
    const values = items?.length ? items : ['None identified.'];
    values.forEach((item, index) => {
      const prefix = numbered ? `${index + 1}. ` : '- ';
      wrapText(`${prefix}${item}`, 88).forEach(value => lines.push({ text: value, size: 9 }));
    });
    lines.push({ text: '', size: 4, gapAfter: 4 });
  };

  section(`What This ${scope === 'domain' ? 'Website' : 'Page'} Sells`, result.whatThisPageSells);
  section('Target Audience', result.whoItIsFor);
  list("What's Working Strong", result.whatIsStrong);
  list('Conversion Bottlenecks & Weaknesses', result.whatIsWeak);
  list('Top Revenue Leaks', result.topConversionLeaks, true);

  if (result.legalTechnicalities) {
    const legal = result.legalTechnicalities;
    section("Derek's Legal & Technicalities Audit", legal.summary);
    section('Compliance Risk Level', (legal.complianceRisk || 'medium').toUpperCase());
    list('Legal DOs & Compliance Strengths', legal.dos);
    list('Legal DONTs & Technical Risks', legal.donts);
  }
  if (result.seasonalRelevance?.applicable) {
    const seasonal = result.seasonalRelevance;
    section('Seasonal Relevance', seasonal.currentSeason ? `Current retail season: ${seasonal.currentSeason}` : 'N/A');
    list('Seasonal Misalignment', seasonal.misalignment || []);
    list('Suggested Seasonal Moves', seasonal.suggestedSeasonalMoves || []);
  }

  section('Best Next Action', result.bestNextMove);
  return lines;
}

export function exportPdfReport(
  result: AuditResult,
  snapshot: PageSnapshot | null,
  scope: string
): void {
  const bytes = buildPdf(reportLines(result, snapshot, scope));
  const pdfBuffer = Uint8Array.from(bytes).buffer;
  const blob = new Blob([pdfBuffer], { type: 'application/pdf' });
  const objectUrl = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = objectUrl;
  let hostname = 'page';
  try {
    if (snapshot?.url) hostname = new URL(snapshot.url).hostname.replace(/[^a-zA-Z0-9.-]/g, '_');
  } catch {
    // Keep the safe fallback filename.
  }
  link.download = `BB_Audit_${hostname}_${new Date().toISOString().slice(0, 10)}.pdf`;
  link.click();
  setTimeout(() => URL.revokeObjectURL(objectUrl), 1000);
}
